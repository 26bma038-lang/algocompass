// Builds src/data/lc_lists.json from scripts/lc-lists.txt.
// Titles, difficulties, premium flags and tags come from LeetCode's GraphQL, never from memory.
// Usage: npm run gen:lc-lists
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const SOURCE = `${root}scripts/lc-lists.txt`;
const TOPICS = `${root}src/data/topics.json`;
const OUT = `${root}src/data/lc_lists.json`;
const LC = "https://leetcode.com/graphql";
const LIST_IDS = { nc: "neetcode150", st: "striver", x: "picks" };
const HEADERS = { "Content-Type": "application/json", Referer: "https://leetcode.com/", Origin: "https://leetcode.com" };

const topics = JSON.parse(fs.readFileSync(TOPICS, "utf8")).topics;
const lcIndex = new Map();
for (const t of topics) for (const tag of t.lcTags) lcIndex.set(tag, [...(lcIndex.get(tag) ?? []), t.id]);
const topicIds = new Set(topics.map((t) => t.id));

const rows = fs
  .readFileSync(SOURCE, "utf8")
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith("#"))
  .map((l) => {
    const [topic, list, slug] = l.split("|").map((s) => s.trim());
    if (!topicIds.has(topic)) throw new Error(`Unknown topic "${topic}" in: ${l}`);
    if (!(list in LIST_IDS)) throw new Error(`Unknown list "${list}" in: ${l}`);
    return { topic, list, slug };
  });

/** LeetCode drops connections now and then: retry with backoff before giving up. */
async function post(body, tries = 4) {
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(LC, { method: "POST", headers: HEADERS, body });
      if (!res.ok) throw new Error(`LeetCode GraphQL answered HTTP ${res.status}`);
      return await res.json();
    } catch (e) {
      if (i >= tries) throw e;
      await new Promise((r) => setTimeout(r, 1500 * i));
    }
  }
}

const slugs = [...new Set(rows.map((r) => r.slug))];
const meta = new Map();
for (let i = 0; i < slugs.length; i += 40) {
  const chunk = slugs.slice(i, i + 40);
  const query =
    "query{" +
    chunk.map((s, j) => `q${j}:question(titleSlug:${JSON.stringify(s)}){title difficulty isPaidOnly topicTags{slug}}`).join(" ") +
    "}";
  const json = await post(JSON.stringify({ query }));
  chunk.forEach((s, k) => meta.set(s, json.data?.[`q${k}`] ?? null));
  await new Promise((r) => setTimeout(r, 800));
}

const missing = slugs.filter((s) => !meta.get(s));
const premium = slugs.filter((s) => meta.get(s)?.isPaidOnly);
if (missing.length) console.error(`Not found on LeetCode (skipped): ${missing.join(", ")}`);
if (premium.length) console.error(`Premium (skipped): ${premium.join(", ")}`);

const rank = { Easy: 0, Medium: 1, Hard: 2 };
const problems = [];
for (const t of topics) {
  const path = rows
    .filter((r) => r.topic === t.id && meta.get(r.slug) && !meta.get(r.slug).isPaidOnly)
    .map((r, i) => ({ r, m: meta.get(r.slug), i }))
    .sort((a, b) => rank[a.m.difficulty] - rank[b.m.difficulty] || a.i - b.i);
  path.forEach(({ r, m }, k) => {
    const tagTopics = [...new Set(m.topicTags.flatMap((x) => lcIndex.get(x.slug) ?? []))];
    problems.push({
      slug: r.slug,
      title: m.title,
      difficulty: m.difficulty,
      topic: t.id,
      topics: [t.id, ...tagTopics.filter((x) => x !== t.id)],
      list: LIST_IDS[r.list],
      order: k + 1,
    });
  });
}

const out = {
  $comment:
    "Generated by scripts/gen-lc-lists.mjs from scripts/lc-lists.txt; edit the .txt and regenerate. Curated LeetCode learning paths per unified topic: NeetCode 150, Striver A2Z / SDE sheet core problems, and AlgoCompass picks for topics both sheets barely cover (non-premium only). `topic` is the learning path a problem belongs to and `order` its 1-based place there (Easy, then Medium, then Hard; list order within a difficulty). `topics` is the path topic plus every topic LeetCode's own tags map to.",
  lists: {
    neetcode150: { name: "NeetCode 150", url: "https://neetcode.io/practice" },
    striver: { name: "Striver A2Z / SDE sheet", url: "https://takeuforward.org/prep-hub/strivers-a2z-dsa-sheet" },
    picks: { name: "AlgoCompass picks", url: null },
  },
  problems,
};
// One problem per line keeps diffs readable.
const body = problems.map((p) => `    ${JSON.stringify(p)}`).join(",\n");
const head = JSON.stringify({ $comment: out.$comment, lists: out.lists }, null, 2).replace(/\n}$/, "");
fs.writeFileSync(OUT, `${head},\n  "problems": [\n${body}\n  ]\n}\n`);

const perTopic = {};
for (const p of problems) perTopic[p.topic] = (perTopic[p.topic] ?? 0) + 1;
console.log(`Wrote ${problems.length} problems to src/data/lc_lists.json`);
console.log(Object.entries(perTopic).map(([k, v]) => `${k} ${v}`).join(", "));
